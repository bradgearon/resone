const fs=require('fs'),path=require('path');
const root=path.resolve(__dirname,'..');
const app=fs.readFileSync(path.join(root,'src/wds.resone.ui/resources/web/app.js'),'utf8');
const win=fs.readFileSync(path.join(root,'native/include/WindowsSupport.hpp'),'utf8');
const cpp=fs.readFileSync(path.join(root,'src/wds.resone.ui/Resone.cpp'),'utf8');
const cmake=fs.readFileSync(path.join(root,'src/wds.resone.ui/CMakeLists.txt'),'utf8');
const ok=(v,m)=>{if(!v)throw Error(m)};
ok(/includeInAi\s*:\s*i\s*===\s*0/.test(app),'fresh song must default only first/Melody lane on');
ok(/name\s*:\s*'Accent '[\s\S]{0,300}includeInAi\s*:\s*false/.test(app),'new lanes must default off for Song mode');
ok(app.includes("if (typeof l.includeInAi !== 'boolean') l.includeInAi = i === 0 || l.name === 'Melody';"),'old projects missing lane flags must migrate Melody-only');
ok(win.includes('SetWindowSubclass(window, standaloneWindowTrackerProc'),'standalone window must use top-level HWND tracker');
ok(win.includes('WM_EXITSIZEMOVE')&&win.includes('WM_CLOSE')&&win.includes('WM_NCDESTROY'),'window tracker must save on Windows lifecycle events');
ok(win.includes('SetTimer(window, kStandaloneWindowRestoreTimerId'),'window restore must be delayed until the APP frame settles');
ok(win.includes('GetWindowRect(window, &r)'),'normal window persistence must save the actual outer frame');
ok(win.includes('SetWindowPos(window, nullptr, x, y, width, height'),'restore must apply the saved outer frame directly');
const resizeBody=cpp.slice(cpp.indexOf('void Resone::OnParentWindowResize'),cpp.indexOf('void Resone::CloseWindow'));
ok(!resizeBody.includes('EditorResizeFromUI('),'parent resize callback must not send a resize request back to the host');
ok(resizeBody.includes('SetEditorSize(width, height)'),'parent resize callback must only synchronize editor bookkeeping');
ok(cpp.includes('resone::trackStandaloneWindowBounds(root);'),'standalone OpenWindow must install tracker');
ok(cmake.includes('comctl32'),'SetWindowSubclass support must link comctl32');
console.log('PASS Melody-only Song defaults and durable standalone window bounds tracking');
