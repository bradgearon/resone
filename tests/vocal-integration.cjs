const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const read = p => fs.readFileSync(path.join(root,p),'utf8');
function ok(v,m){ if(!v) throw new Error(m); }
const app = read('src/wds.resone.ui/resources/web/app.js');
const html = read('src/wds.resone.ui/resources/web/index.html');
const worker = read('src/wds.resone.launcher/WorkerHost.cs');
const forge = read('src/wds.resone.api/ForgeEngine.cs');
const qwen = read('src/wds.resone.api/VocalSinging/QwenTtsRuntime.cs');
const models = read('src/wds.resone.api/VocalSinging/VocalSingingModels.cs');
const hdr = read('native/vendor/qwen/qwen_resone_abi.h');
const cfg = JSON.parse(read('config/appsettings.json'));
const runtime = JSON.parse(read('config/runtime.json'));
ok(app.includes("'Vocals'"), 'Vocals lane missing');
ok(app.includes('vocals : i === 6'), 'Vocals lane type default missing');
ok(app.includes('includeInAi : i === 0'), 'Only Melody should be checked by default');
ok(html.includes('id="vocalLyrics"') && html.includes('id="vocalVoice"') && html.includes('id="renderVocals"'), 'Vocal UI missing');
ok(worker.includes('case "renderVocals"'), 'renderVocals worker op missing');
ok(forge.includes('QwenTtsRuntime.SharedAsync') && forge.includes('VocalSingingEngine'), 'Qwen -> singing pipeline missing');
ok(forge.includes('VowelHold = 1.25f') && forge.includes('ConsonantDrive = .7f'), 'Requested guidance defaults missing');
ok(models.includes('SlideSeconds { get; init; } = .12f') && models.includes('VowelHold { get; init; } = 1.25f') && models.includes('ConsonantDrive { get; init; } = .7f'), 'VocalGuidanceEvent defaults missing');
ok(!qwen.includes('tts-server.exe') && !qwen.includes('HttpClient'), 'Qwen must be direct DLL, not HTTP/server');
ok(qwen.includes('NativeLibrary.Load') && qwen.includes('qt_synthesize'), 'Direct qwen DLL binding missing');
ok(qwen.includes('public byte DoSample') && qwen.includes('public byte SubtalkerDoSample'), 'qwentts ABI v4 sampling bools missing');
ok(!qwen.includes('qt_model_type'), 'Pinned qwentts commit has no qt_model_type export');
ok(qwen.includes('a8a7716b530e49fed537c57711247c12fbbb903c'), 'Qwen commit pin missing');
ok(hdr.includes('#define QT_ABI_VERSION 4') && hdr.includes('bool do_sample;') && hdr.includes('bool subtalker_do_sample;'), 'Vendored qwentts ABI snapshot is not v4');
ok(cfg.qwenTtsExpectedVersionPrefix === 'a8a7716', 'Qwen expected version prefix config mismatch');
ok(cfg.qwenTtsMode === 'auto', 'Qwen mode config missing');
ok(runtime.enginePacks.some(x => x.directory === 'engines/tts/qwentts-cpp-dynamic-win-x64'), 'Qwen engine pack entry missing');
console.log('PASS vocals lane, singing pipeline, qwentts.cpp ABI v4 pin, and Melody-only song default');
