const fs=require('fs');
const assert=require('assert');
const read=p=>fs.readFileSync(p,'utf8');
const app=JSON.parse(read('config/appsettings.json'));
assert.strictEqual(app.useLocalWhisper,true,'local whisper should be enabled');
assert.strictEqual(app.whisperEngineDirectories['win-x64'],'engines/asr/whispercpp-nvidia-win-x64','wrong Windows whisper pack');
assert.strictEqual(app.qwenTtsEngineDirectories['win-x64'],'engines/tts/qwenttscpp-nvidia-win-x64','wrong Windows Qwen pack');
const runtime=read('src/wds.resone.api/WhisperCppRuntime.cs');
assert(runtime.includes('whisper-server.exe'),'bundled whisper server discovery missing');
assert(runtime.includes('ReserveLoopbackPort'),'private lazy loopback runtime missing');
assert(runtime.includes('WarmAsync'),'whisper warmup missing');
assert(runtime.includes('CreateNoWindow = true'),'whisper child must stay hidden');
const worker=read('src/wds.resone.launcher/WorkerHost.cs');
assert(worker.includes('request.Op == "asrWarm"'),'background ASR warm operation missing');
assert(worker.includes('speechService.WarmTranscriptionAsync'),'worker does not warm shared speech service');
const js=read('src/wds.resone.ui/resources/web/app.js');
const start=js.indexOf("send('voiceStart', {}, id)");
const warm=js.indexOf("send('asrWarm', {}, crypto.randomUUID())");
assert(start>=0 && warm>start,'recording must start before async whisper warmup');
assert(js.includes("$('voicePreviewStatus').textContent = 'Error: ' + message"),'voice designer error is not surfaced in-dialog');
assert(js.includes("['voiceDesignPreview','voiceImportPreview','voiceSavePreview'].includes(failedKind)"),'voice failures do not clear the pending UI state');
const voice=read('src/wds.resone.api/VocalSinging/VoiceService.cs');
assert(voice.includes('SpeechService speechService'),'VoiceService should share the warmed ASR runtime');
assert(!voice.includes('new SpeechService(http, settings).TranscribeAsync'),'voice designer must not spawn a second ASR runtime');
console.log('PASS lazy bundled whisper warmup, corrected Qwen path, shared ASR, and voice-designer error recovery');
