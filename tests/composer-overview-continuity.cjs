const fs=require('node:fs');
const read=p=>fs.readFileSync(p,'utf8');
const must=(v,m)=>{if(!v)throw new Error(m)};
const ui=read('src/wds.resone.ui/resources/web/app.js');
const forge=read('src/wds.resone.api/ForgeEngine.cs');
const arranger=read('src/wds.resone.api/ArrangementComposer.cs');
const planner=read('src/wds.resone.api/MusicNarrativePlanner.cs');
const producer=read('src/wds.resone.api/SongCompositionDesigner.cs');
const pass=read('src/wds.resone.api/SongComposerDesignPass.cs');
const store=read('src/wds.resone.api/SongWorkspaceStore.cs');
must(ui.includes('workspaceComposerOverview'), 'browser has no persistent composer overview state');
must(ui.includes('composerOverview :') && ui.includes('workspaceComposerOverview'), 'future requests omit composer overview');
must(store.includes('ComposerDesign') && store.includes('composerDesign'), 'workspace does not save/load composer overview');
must(forge.includes('composerOverview') && forge.includes('existingComposerOverview'), 'API does not accept composer overview context');
must(arranger.includes('EXISTING SONG COMPOSER OVERVIEW — PERSISTENT MUSICAL DNA'), 'normal lane composer does not receive composer overview');
must(planner.includes('EXISTING SONG COMPOSER OVERVIEW'), 'narrative planner does not receive composer overview');
must(producer.includes('EXISTING SONG COMPOSER OVERVIEW'), 'future full-song producer does not receive composer overview');
must(pass.includes('EXISTING SONG COMPOSER OVERVIEW'), 'future composer design pass does not receive previous overview');
console.log('PASS composer overview survives workspaces and is included in all later modification/full-song requests');
