const fs=require('fs'), assert=require('assert');
const read=p=>fs.readFileSync(p,'utf8');
const manager=read('src/wds.resone.api/VocalSinging/QwenTtsServiceManager.cs');
const settings=read('src/wds.resone.api/Contracts.cs');
const app=JSON.parse(read('config/appsettings.json'));
assert(manager.includes('qwen-server.exe') && manager.includes('tts-server.exe'),'managed qwen server discovery missing');
assert(manager.includes('/health'),'qwen server health probe missing');
assert(manager.includes('/v1/audio/speech'),'qwen speech endpoint missing');
assert(manager.includes('/v1/audio/voices'),'reference voice registry endpoint missing');
assert(manager.includes('SetScopeActiveAsync'),'voice designer scope pin missing');
assert(manager.includes('ActivityAsync'),'TTS activity API missing');
assert(manager.includes('ScheduleIdleStopLocked'),'idle shutdown timer missing');
assert(manager.includes('process.Kill(entireProcessTree: true)'),'managed server termination missing');
assert(manager.includes('QwenTtsServiceKind.VoiceDesign') && manager.includes('QwenTtsServiceKind.CustomVoice'),'separate service modes missing');
assert(settings.includes('ServiceDelays'),'serviceDelays settings missing');
assert.deepStrictEqual(app.serviceDelays,{'voice-design':3000,'custom-voice':3000});
assert.strictEqual(app.qwenTtsServerName,'qwen-server.exe');
assert(!fs.existsSync('src/wds.resone.api/VocalSinging/QwenTtsRuntime.cs'),'obsolete in-process Qwen runtime still present');
const ps=read('scripts/build-qwentts-nvidia-win-x64.ps1');
assert(ps.includes("'--target','tts-server'"),'pinned server build target missing');
assert(ps.includes("Join-Path $Stage 'qwen-server.exe'"),'server staging name missing');
assert(!ps.includes('-DQWEN_SHARED=ON'),'server pack should not require shared qwen.dll');
assert(ps.includes("submodule','update','--init','--recursive','--force"),'pinned GGML submodule update missing');
console.log('PASS managed qwentts server lifecycle, service delays, and pinned NVIDIA server staging');
